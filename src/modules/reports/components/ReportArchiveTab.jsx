import React, { useState } from 'react';
import {
  FileText,
  FileSpreadsheet,
  Download,
  Trash2,
  Eye,
  Search,
  Filter,
  Plus,
  Calendar,
  CheckCircle2,
} from 'lucide-react';
import { Table, Button, StatusPill } from '@/design-system';

export function ReportArchiveTab({
  reports,
  isLoading,
  onOpenCreate,
  onViewSnapshot,
  onDownload,
  onDelete,
  canManage,
}) {
  const [searchQuery, setSearchQuery] = useState('');
  const [formatFilter, setFormatFilter] = useState('ALL');

  const filteredReports = (reports ?? []).filter((report) => {
    const matchesSearch =
      !searchQuery ||
      report.name?.toLowerCase().includes(searchQuery.toLowerCase()) ||
      report.period?.toLowerCase().includes(searchQuery.toLowerCase()) ||
      report.author?.toLowerCase().includes(searchQuery.toLowerCase());

    const matchesFormat =
      formatFilter === 'ALL' ||
      (formatFilter === 'PDF' && report.format?.includes('PDF')) ||
      (formatFilter === 'EXCEL' && (report.format?.includes('Excel') || report.format?.includes('Spreadsheet')));

    return matchesSearch && matchesFormat;
  });

  const columns = [
    {
      key: 'name',
      header: 'Report Title & Category',
      render: (row) => (
        <div className="flex items-center gap-3">
          <div className="flex h-9 w-9 shrink-0 items-center justify-center rounded-lg bg-brand-50 text-brand-700 border border-brand-100">
            {row.format?.includes('Excel') ? (
              <FileSpreadsheet className="h-4 w-4 text-emerald-600" />
            ) : (
              <FileText className="h-4 w-4 text-brand-600" />
            )}
          </div>
          <div>
            <span className="font-semibold text-ink-900 block">{row.name}</span>
            <span className="text-[11px] text-ink-400">
              Type: <strong className="text-ink-600">{row.type || 'EXECUTIVE'}</strong> • Generated by {row.author || 'System'}
            </span>
          </div>
        </div>
      ),
    },
    {
      key: 'period',
      header: 'Reporting Period',
      render: (row) => (
        <span className="font-medium text-xs text-ink-700">{row.period}</span>
      ),
    },
    {
      key: 'generatedAt',
      header: 'Generated Date',
      render: (row) => (
        <span className="text-xs text-ink-500 font-mono">{row.generatedAt || 'Just now'}</span>
      ),
    },
    {
      key: 'format',
      header: 'Format & Size',
      render: (row) => (
        <div className="flex items-center gap-2">
          <span className="px-2 py-0.5 rounded-full text-[11px] font-semibold bg-slate-100 text-ink-700 border border-slate-200">
            {row.format}
          </span>
          <span className="text-[11px] text-ink-400 font-mono">{row.size || '2.1 MB'}</span>
        </div>
      ),
    },
    {
      key: 'actions',
      header: 'Actions',
      align: 'right',
      render: (row) => (
        <div className="flex items-center justify-end gap-1.5">
          <button
            type="button"
            onClick={() => onViewSnapshot(row)}
            title="Preview Snapshot"
            className="flex h-8 w-8 items-center justify-center rounded-lg text-ink-500 transition-colors hover:bg-brand-50 hover:text-brand-700"
          >
            <Eye className="h-4 w-4" />
          </button>
          <button
            type="button"
            onClick={() => onDownload(row)}
            title="Download Report"
            className="flex h-8 w-8 items-center justify-center rounded-lg text-ink-500 transition-colors hover:bg-emerald-50 hover:text-emerald-700"
          >
            <Download className="h-4 w-4" />
          </button>
          {canManage && (
            <button
              type="button"
              onClick={() => onDelete(row.id)}
              title="Delete Archive"
              className="flex h-8 w-8 items-center justify-center rounded-lg text-ink-400 transition-colors hover:bg-rose-50 hover:text-rose-600"
            >
              <Trash2 className="h-4 w-4" />
            </button>
          )}
        </div>
      ),
    },
  ];

  return (
    <div className="flex flex-col gap-5">
      {/* Search & Actions Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 p-4 bg-white rounded-xl border border-surface-border">
        <div className="flex flex-wrap items-center gap-2.5 flex-1">
          {/* Search */}
          <div className="flex items-center gap-2 rounded-lg border border-surface-border bg-slate-50/50 px-3 py-1.5 text-xs flex-1 max-w-sm">
            <Search className="h-3.5 w-3.5 text-ink-400 shrink-0" />
            <input
              type="text"
              placeholder="Search reports by title, period, or author…"
              value={searchQuery}
              onChange={(e) => setSearchQuery(e.target.value)}
              className="bg-transparent outline-none w-full text-ink-800 placeholder:text-ink-400"
            />
          </div>

          {/* Format Filter */}
          <select
            value={formatFilter}
            onChange={(e) => setFormatFilter(e.target.value)}
            className="rounded-lg border border-surface-border bg-white px-3 py-1.5 text-xs font-semibold text-ink-700 shadow-2xs focus:border-brand-500 focus:outline-none"
          >
            <option value="ALL">All Formats</option>
            <option value="PDF">PDF Documents</option>
            <option value="EXCEL">Excel Workbooks</option>
          </select>
        </div>

        {canManage && (
          <Button size="sm" onClick={onOpenCreate} className="flex items-center gap-1.5 shadow-sm">
            <Plus className="h-3.5 w-3.5" />
            Schedule New Report
          </Button>
        )}
      </div>

      {/* Reports Table */}
      <div className="bg-white rounded-xl border border-surface-border shadow-2xs overflow-hidden">
        <Table
          columns={columns}
          data={filteredReports}
          rowKey={(row) => row.id}
          isLoading={isLoading}
        />
      </div>
    </div>
  );
}
